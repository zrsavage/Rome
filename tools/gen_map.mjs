// Generates src/mapdata.js from real Natural Earth data (public domain).
//   node tools/gen_map.mjs <rivers.geojson> <lakes.geojson>
// Land comes from the `world-atlas` npm package (land-10m). Mercator, lon -11..44, lat 29..58.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoMercator, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';
import { presimplify, simplify } from 'topojson-simplify';
const require = createRequire(import.meta.url);

const [riversFile, lakesFile] = process.argv.slice(2);
const LON0 = -11, LON1 = 44, LAT0 = 29, LAT1 = 58, W = 3300;
const rad = (d) => d * Math.PI / 180, merc = (lat) => Math.log(Math.tan(Math.PI / 4 + rad(lat) / 2));
const s = W / rad(LON1 - LON0), tx = -s * rad(LON0), ty = s * merc(LAT1), H = Math.round(s * (merc(LAT1) - merc(LAT0)));
const proj = geoMercator().scale(s).translate([tx, ty]).precision(0.3).clipExtent([[-5, -5], [W + 5, H + 5]]);
const path = geoPath(proj).digits(1);

// land
const topo = require('world-atlas/land-10m.json');
const simp = simplify(presimplify(topo), 4e-4);
const land = path(feature(simp, simp.objects.land));

// lakes: keep the larger ones inside the box
const inBox = (g) => { const b = geoPath(proj).bounds(g); return b[1][0] > 0 && b[0][0] < W && b[1][1] > 0 && b[0][1] < H; };
const lakes = JSON.parse(readFileSync(lakesFile, 'utf8')).features.filter(f => inBox(f) && geoPath(proj).area(f) > 400);   // only the large lakes (Lemannus, Brigantinus, the Alpine lakes)
const lakePath = lakes.map(f => path(f)).join('');

// rivers: project, clip to box, Douglas-Peucker
function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let md = 0, mi = -1;
    const [x1, y1] = pts[a], [x2, y2] = pts[b], dx = x2 - x1, dy = y2 - y1, L = Math.hypot(dx, dy) || 1;
    for (let i = a + 1; i < b; i++) { const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / L; if (d > md) { md = d; mi = i; } }
    if (md > tol && mi > 0) { keep[mi] = 1; stack.push([a, mi], [mi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
// Only rivers that matter to the campaigns are drawn, in two tiers: the great rivers (shown on the whole-world view too) and the
// rivers of the theatres of war (shown when zoomed to an act). Hundreds of minor streams made the map unreadable.
const MAJOR = /^(Rhein|Rhin|Rhine|Danube|Donau|Rhône|Nile|Euphrates|Firat|Tigris|Dicle|Po|Ebro|Loire|Seine|Tevere|Thames|Elbe|Garonne|Tajo|Tejo)$/;
const THEATRE = /^(Sane|Doubs|Mosel|Maas|Marne|Yonne|Dordogne|Durance|Main|Schelde|Adige|Inn|Weser|Duero|Guadalquivir|Sava|Jordan|Morava)$/;
const riverFeatures = JSON.parse(readFileSync(riversFile, 'utf8')).features;
function riversFor(re, tol) {
  let out = '';
  for (const f of riverFeatures.filter(f => re.test(f.properties.name || ''))) {
    const lines = f.geometry.type === 'MultiLineString' ? f.geometry.coordinates : [f.geometry.coordinates];
    for (const ln of lines) {
      const pts = ln.map(c => proj(c)).filter(Boolean);
      let seg = [];
      const flush = () => { if (seg.length > 1) { const d = dp(seg, tol); out += 'M' + d.map(p => p[0].toFixed(1) + ' ' + p[1].toFixed(1)).join('L'); } seg = []; };
      for (const p of pts) { if (p[0] >= -5 && p[0] <= W + 5 && p[1] >= -5 && p[1] <= H + 5) seg.push(p); else flush(); }
      flush();
    }
  }
  return out;
}
const riverPath = riversFor(MAJOR, 0.45), riverMinor = riversFor(THEATRE, 0.45);
const nameList = new Set(riverFeatures.filter(f => MAJOR.test(f.properties.name || '') || THEATRE.test(f.properties.name || '')).map(f => f.properties.name));

const out = `// GENERATED by tools/gen_map.mjs from Natural Earth (public domain). Do not edit by hand.
export const MAP = { W: ${W}, H: ${H}, s: ${s.toFixed(3)}, tx: ${tx.toFixed(3)}, ty: ${ty.toFixed(3)}, lon0: ${LON0}, lon1: ${LON1}, lat0: ${LAT0}, lat1: ${LAT1},
  land: ${JSON.stringify(land)},
  lakes: ${JSON.stringify(lakePath)},
  rivers: ${JSON.stringify(riverPath)},
  riversMinor: ${JSON.stringify(riverMinor)} };
`;
writeFileSync('src/mapdata.js', out);
console.log(`map ${W}x${H}  land ${(land.length / 1024).toFixed(0)}KB  lakes ${lakes.length} (${(lakePath.length / 1024).toFixed(0)}KB)  rivers ${nameList.size} (${(riverPath.length / 1024).toFixed(0)}KB) total ${(out.length / 1024).toFixed(0)}KB`);
console.log([...nameList].filter(n => /Rh|Sa|Seine|Loire|Rhine|Danube|Po$|Tiber|Garonne|Marne|Moselle|Meuse|Thames|Elbe/i.test(n || '')).join(', '));
